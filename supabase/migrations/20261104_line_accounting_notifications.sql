-- LINE OA daily accounting reminders. All tables are private and service-role only.
create table if not exists public.line_notification_config (
  id integer primary key default 1 check (id = 1),
  group_id text not null,
  updated_at timestamptz not null default now()
);
alter table public.line_notification_config enable row level security;
revoke all on public.line_notification_config from public, anon, authenticated;

create table if not exists public.line_notification_runs (
  id bigint generated by default as identity primary key,
  run_date date not null unique,
  status text not null default 'sending' check (status in ('sending','sent')),
  sent_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.line_notification_runs enable row level security;
revoke all on public.line_notification_runs from public, anon, authenticated;
