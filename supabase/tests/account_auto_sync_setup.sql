create extension if not exists pgcrypto;

create table public.accounts (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  price numeric(12,2) not null default 0,
  status text not null default 'available' check (status in ('available','installment','sold')),
  image_url text not null default '',
  installment_details text not null default '',
  sale_started_at timestamptz,
  accounting_carryover boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.account_private_financials (
  account_id bigint primary key references public.accounts(id) on delete cascade,
  acquisition_cost numeric(12,2) not null default 0 check (acquisition_cost >= 0),
  installment_due_weekday smallint check (installment_due_weekday is null or installment_due_weekday between 0 and 6),
  accounting_handoff_at timestamptz,
  actual_sale_price numeric(12,2) check (actual_sale_price is null or actual_sale_price >= 0),
  updated_at timestamptz not null default now()
);

create table public.accounting_entries (
  id uuid primary key default gen_random_uuid(),
  source_account_id bigint references public.accounts(id) on delete set null,
  account_title text not null,
  sale_date date not null,
  sale_amount numeric(12,2) not null default 0 check (sale_amount >= 0),
  cost_amount numeric(12,2) not null default 0 check (cost_amount >= 0),
  opening_balance numeric(12,2) not null default 0 check (opening_balance >= 0),
  weekly_amount numeric(12,2) not null default 0 check (weekly_amount >= 0),
  installment_due_weekday smallint check (installment_due_weekday is null or installment_due_weekday between 0 and 6),
  is_carryover boolean not null default false,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index accounting_entries_source_account_unique
  on public.accounting_entries(source_account_id)
  where source_account_id is not null;

create table public.accounting_payments (
  id uuid primary key default gen_random_uuid(),
  entry_id uuid not null references public.accounting_entries(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  paid_on date not null default current_date,
  payment_type text not null default 'installment'
    check (payment_type in ('deposit','installment','other')),
  note text not null default '',
  created_at timestamptz not null default now()
);

