-- Public customer reviews enter moderation queue; only admin can publish/edit/delete.
create table if not exists public.site_settings (
  id integer primary key default 1 check (id = 1),
  shop_name text not null default 'jellybet',
  intro text not null default 'ยินดีต้อนรับสู่หน้ารวมเครดิตและช่องทางติดต่อของร้านนะคะ ขอบคุณที่ไว้วางใจและสนับสนุนกันเสมอ ♡',
  handle text not null default 'a little place made with love',
  status text not null default 'open' check (status in ('open','closed')),
  line text not null default '', x text not null default '', instagram text not null default '', facebook text not null default '',
  avatar_url text not null default '', cover_url text not null default '',
  updated_at timestamptz not null default now()
);
insert into public.site_settings (id) values (1) on conflict (id) do nothing;
alter table public.site_settings add column if not exists avatar_url text not null default '';
alter table public.site_settings add column if not exists cover_url text not null default '';

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(customer_name) between 1 and 60),
  rating integer not null default 5 check (rating between 1 and 5),
  review_text text not null check (char_length(review_text) between 1 and 1000),
  image_url text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings for select using (true);
drop policy if exists "Admins can insert site settings" on public.site_settings;
create policy "Admins can insert site settings" on public.site_settings for insert to authenticated with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Admins can update site settings" on public.site_settings;
create policy "Admins can update site settings" on public.site_settings for update to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin') with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Public can read published reviews" on public.reviews;
create policy "Public can read published reviews" on public.reviews for select using (published = true or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Customers can submit pending reviews" on public.reviews;
create policy "Customers can submit pending reviews" on public.reviews for insert to anon, authenticated with check (published = false and char_length(customer_name) between 1 and 60 and char_length(review_text) between 1 and 1000 and rating between 1 and 5);
drop policy if exists "Admins can insert reviews" on public.reviews;
create policy "Admins can insert reviews" on public.reviews for insert to authenticated with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Admins can update reviews" on public.reviews;
create policy "Admins can update reviews" on public.reviews for update to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin') with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
drop policy if exists "Admins can delete reviews" on public.reviews;
create policy "Admins can delete reviews" on public.reviews for delete to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Public images are served by URL; uploads are separately restricted by Storage RLS.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
 ('review-images','review-images',true,5242880,array['image/jpeg','image/png','image/webp','image/gif']),
 ('shop-images','shop-images',true,5242880,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=excluded.public, file_size_limit=excluded.file_size_limit, allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists "Anyone can upload review images" on storage.objects;
create policy "Anyone can upload review images" on storage.objects for insert to anon, authenticated with check (bucket_id = 'review-images' and (storage.foldername(name))[1] = 'customer');
drop policy if exists "Admins can upload shop images" on storage.objects;
create policy "Admins can upload shop images" on storage.objects for insert to authenticated with check (bucket_id = 'shop-images' and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin' and (storage.foldername(name))[1] = 'admin');
drop policy if exists "Admins can delete jellybet images" on storage.objects;
create policy "Admins can delete jellybet images" on storage.objects for delete to authenticated using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin' and bucket_id in ('review-images','shop-images'));

